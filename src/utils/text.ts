const createStopwordSet = (words: string[]): Set<string> => {
  return new Set(words.map((word) => normalizeTextToken(word.trim())));
};

// Keep lists embedded so the package stays portable after being published to npm.
const STOPWORDS_BY_INPUT_LANGUAGE: Record<TextInputLanguage, Set<string>> = {
  en: createStopwordSet(EN_STOPWORDS),
  'pt-BR': createStopwordSet(PT_BR_STOPWORDS),
};

export const getStopwordsForLanguage = (
  inputLanguage: TextInputLanguage,
): Set<string> => {
  return STOPWORDS_BY_INPUT_LANGUAGE[inputLanguage];
};
